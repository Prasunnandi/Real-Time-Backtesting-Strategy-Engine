"""
Event classes for the Event-Driven Backtesting and Execution Engine.
Decouples Market Data, Alpha Generation, Portfolio Risk, and Broker Execution.
"""

from dataclasses import dataclass
from typing import Optional

class Event:
    """Base class for all discrete backtest events."""
    pass

@dataclass
class MarketEvent(Event):
    """Triggered when new tick or bar data is received."""
    symbol: str
    timestamp: str
    open: float
    high: float
    low: float
    close: float
    volume: int

@dataclass
class SignalEvent(Event):
    """Emitted by Strategy when an alpha condition triggers."""
    symbol: str
    timestamp: str
    signal_type: str  # 'LONG', 'SHORT', 'EXIT'
    strength: float = 1.0
    strategy_id: str = "DEFAULT"

@dataclass
class OrderEvent(Event):
    """Generated by Portfolio manager and sent to Execution broker."""
    symbol: str
    order_type: str   # 'MKT', 'LMT'
    quantity: int
    direction: str    # 'BUY', 'SELL'
    limit_price: Optional[float] = None

@dataclass
class FillEvent(Event):
    """Encapsulates execution fill details including slippage and commissions."""
    timestamp: str
    symbol: str
    exchange: str
    quantity: int
    direction: str
    fill_price: float
    commission: float
    slippage: float
